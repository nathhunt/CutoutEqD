using System;
using System.Collections.Generic;
using System.Globalization;

namespace CutoutEqD.Core;

/// <summary>Everything that goes on the one-page PDF measurement record.</summary>
public sealed class ReportData
{
    public string ImageName { get; set; } = "";
    public DateTime Date { get; set; } = DateTime.Now;
    public string AppVersion { get; set; } = "";

    /// <summary>The (rotated / cropped) image as JPEG, and its pixel size.</summary>
    public byte[] Jpeg { get; set; } = Array.Empty<byte>();
    public int JpegWidth { get; set; }
    public int JpegHeight { get; set; }
    public int JpegComponents { get; set; } = 3;

    /// <summary>Size of the image the geometry below refers to (may differ from the JPEG if it was downsampled).</summary>
    public int ImageWidth { get; set; }
    public int ImageHeight { get; set; }

    public IReadOnlyList<Pt> Outline { get; set; } = Array.Empty<Pt>();
    public Pt ScaleA { get; set; }
    public Pt ScaleB { get; set; }
    public double KnownDistanceMm { get; set; }
    public double MmPerPixel { get; set; }
    public string ThresholdDescription { get; set; } = "";
}

/// <summary>Lays out the measurement record: header, results, the annotated image and a method note.</summary>
public static class ReportBuilder
{
    // Colours match the app (Windows accent blue; outline green and scale magenta as on screen).
    private static readonly (byte r, byte g, byte b) Accent = (0, 95, 184), Ink = (27, 27, 27), Muted = (97, 97, 97),
        Hairline = (220, 220, 220), OutlineGreen = (20, 170, 50), OutlineFill = (255, 210, 0), ScaleMagenta = (220, 0, 200);

    public static byte[] Build(ReportData d)
    {
        var m = FieldMetrics.From(d.Outline, d.MmPerPixel);
        var pg = new PdfPage();
        const double margin = 42;
        double left = margin, right = pg.Width - margin, width = right - left;
        double y = pg.Height - margin;

        // Header
        y -= 18;
        Color(pg, Ink).Text(left, y, PdfFont.HelveticaBold, 18, "Cutout equivalent diameter");
        y -= 16;
        Color(pg, Muted).Text(left, y, PdfFont.Helvetica, 9.5,
            $"{d.ImageName}  ·  {d.Date.ToString("d MMMM yyyy, HH:mm", CultureInfo.CurrentCulture)}");
        y -= 12;
        Stroke(pg, Hairline).LineWidth(0.75).Line(left, y, right, y);

        // Results: big EqD on the left, table on the right.
        double top = y - 22;
        Color(pg, Muted).Text(left, top, PdfFont.Helvetica, 9.5, "Equivalent diameter");
        Color(pg, Accent).Text(left, top - 34, PdfFont.HelveticaBold, 32, $"{m.EquivalentDiameterCm:F2} cm");
        Color(pg, Muted).Text(left, top - 52, PdfFont.Helvetica, 8.5, "EqD = 2√(A/π)");

        var rows = new List<(string, string)>
        {
            ("Area", $"{m.AreaCm2:F2} cm²"),
            ("Perimeter", $"{m.PerimeterCm:F2} cm"),
            ("4A/P", $"{m.FourAOverPCm:F2} cm"),
            ("Scale", $"{1 / d.MmPerPixel:F3} px/mm  ({25.4 / d.MmPerPixel:F0} dpi)"),
            ("Scale reference", $"{d.KnownDistanceMm:0.##} mm over {Pt.Distance(d.ScaleA, d.ScaleB):F1} px"),
            ("Edge threshold", d.ThresholdDescription),
            ("Outline vertices", d.Outline.Count.ToString(CultureInfo.CurrentCulture)),
        };
        double tableLeft = left + width * 0.45, rowH = 17, ty = top + 4;
        foreach (var (caption, value) in rows)
        {
            if (string.IsNullOrEmpty(value)) continue;
            Color(pg, Muted).Text(tableLeft, ty - 11, PdfFont.Helvetica, 9, caption);
            Color(pg, Ink).TextRight(right, ty - 11, PdfFont.Helvetica, 9, value);
            ty -= rowH;
            Stroke(pg, Hairline).LineWidth(0.5).Line(tableLeft, ty, right, ty);
        }
        y = Math.Min(top - 64, ty) - 18;

        // Footer (laid out first so the image can take the remaining space).
        const double noteSize = 8;
        var note = PdfPage.Wrap(PdfFont.Helvetica, noteSize,
            "EqD is the diameter of the circle with the same area as the outline, the conversion used to look up " +
            "circular-field kilovoltage data such as backscatter factors (IPEMB 1996; AAPM TG-61, 2001). 4A/P (Sterling et al. 1964) " +
            "is shown for reference. Confirm the method matches your department's protocol, and check the outline in the image above.",
            width);
        double footerTop = margin + 14 + note.Count * (noteSize + 3) + 8;
        double ny = footerTop - 8 - noteSize;
        foreach (var line in note) { Color(pg, Muted).Text(left, ny, PdfFont.Helvetica, noteSize, line); ny -= noteSize + 3; }
        Stroke(pg, Hairline).LineWidth(0.5).Line(left, margin + 10, right, margin + 10);
        Color(pg, Muted).Text(left, margin, PdfFont.Helvetica, 7.5, "Generated by Cutout Equivalent Diameter " + d.AppVersion);
        Color(pg, Muted).TextRight(right, margin, PdfFont.Helvetica, 7.5, "Page 1 of 1");

        // Image, fitted into the space between results and footer.
        double boxTop = y, boxBottom = footerTop + 6, boxH = boxTop - boxBottom;
        if (d.Jpeg.Length > 0 && boxH > 50 && d.ImageWidth > 0 && d.ImageHeight > 0)
        {
            double s = Math.Min(width / d.ImageWidth, boxH / d.ImageHeight);
            double iw = d.ImageWidth * s, ih = d.ImageHeight * s;
            double ix = left + (width - iw) / 2, iy = boxTop - ih;
            pg.Image(d.Jpeg, d.JpegWidth, d.JpegHeight, d.JpegComponents, ix, iy, iw, ih);

            // Overlays in vector form, clipped to the image.
            double X(Pt p) => ix + p.X * s;
            double Y(Pt p) => iy + ih - p.Y * s;
            pg.Save().Rect(ix, iy, iw, ih).Clip();
            if (d.Outline.Count >= 3)
            {
                void Path() { pg.MoveTo(X(d.Outline[0]), Y(d.Outline[0])); for (int i = 1; i < d.Outline.Count; i++) pg.LineTo(X(d.Outline[i]), Y(d.Outline[i])); pg.Close(); }
                pg.Save().Alpha(0.22); Color(pg, OutlineFill); Path(); pg.FillPath().Restore();
                Stroke(pg, OutlineGreen).LineWidth(1.2).LineJoinRound(); Path(); pg.StrokePath();
            }
            Pt a = d.ScaleA, b = d.ScaleB;
            Stroke(pg, ScaleMagenta).LineWidth(1).Line(X(a), Y(a), X(b), Y(b));
            foreach (var p in new[] { a, b })
            {
                pg.Line(X(p) - 5, Y(p), X(p) + 5, Y(p));
                pg.Line(X(p), Y(p) - 5, X(p), Y(p) + 5);
            }
            string label = $"{d.KnownDistanceMm:0.##} mm";
            double lw = PdfPage.TextWidth(PdfFont.HelveticaBold, 8, label);
            double lx = (X(a) + X(b)) / 2, ly = (Y(a) + Y(b)) / 2 + 8;
            pg.Save().Alpha(0.8).Fill(20, 20, 20).RoundedRect(lx - lw / 2 - 4, ly - 3, lw + 8, 13, 6.5).FillPath().Restore();
            Color(pg, ScaleMagenta).TextCentered(lx, ly + 0.5, PdfFont.HelveticaBold, 8, label);
            pg.Restore();
            Stroke(pg, Hairline).LineWidth(0.75).Rect(ix, iy, iw, ih).StrokePath();
        }

        return pg.ToBytes("Cutout equivalent diameter — " + d.ImageName);
    }

    private static PdfPage Color(PdfPage pg, (byte r, byte g, byte b) c) => pg.Fill(c.r, c.g, c.b);
    private static PdfPage Stroke(PdfPage pg, (byte r, byte g, byte b) c) => pg.Stroke(c.r, c.g, c.b);
}
